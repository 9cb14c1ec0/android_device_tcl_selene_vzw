#!/usr/bin/env python3
"""Generate the Android 13 Codec2 framework used by the stock codec blobs.

The MediaTek Codec2 service and its components were built against the
Android 13 Codec2 framework. Mixing the stock copies of part of it
(libcodec2_vndk, libcodec2_hidl, ...) with Android 16 source builds of the
rest (libcodec2, libui, libstagefright_bufferqueue_helper) breaks: Android 16
libbase/bufferqueue_helper dropped entry points, and libui/libcodec2 changed
class layouts. This copies the stock/VNDK 33 libraries, renames them with a
-v33 suffix and relinks them among themselves; extract-files.py points the
codec blobs at the renamed names. 64-bit only (the 64b service is the one
started).

Usage: generate.py <stock vendor dump> (the dir holding lib64/)
"""
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOP = os.path.abspath(os.path.join(HERE, '../../../../..'))
PATCHELF = os.path.join(TOP, 'prebuilts/extract-tools/linux-x86/bin/patchelf-0_17_2')
VNDK33 = os.path.join(TOP, 'prebuilts/vndk/v33/arm64/arch-arm64-armv8-a/shared/vndk-core')

# name -> source ('stock' vendor/lib64, 'vndk33', or 'lineage' for a -v33
# library hardware/lineage/compat already provides; relink only)
LIBS = {
    'libcodec2': 'vndk33',
    'libstagefright_foundation': 'lineage',
    'libstagefright_bufferqueue_helper': 'vndk33',
    # GraphicBuffer is constructed inline by libcodec2_vndk; its layout changed.
    'libui': 'vndk33',
    'libcodec2_vndk': 'stock',
    'libcodec2_soft_common': 'stock',
    'libsfplugin_ccodec_utils': 'stock',
    'libcodec2_hidl@1.0': 'stock',
    'libcodec2_hidl@1.1': 'stock',
    'libcodec2_hidl@1.2': 'stock',
    'libcodec2_hidl_plugin': 'stock',
    'libstagefright_bufferpool@2.0.1': 'stock',
}

# Same AIDL version bumps as the other blobs (extract-files.py): Android 16
# vendor ships graphics.common-V7 and allocator-V2 only.
REPLACE = {
    'android.hardware.graphics.common-V3-ndk.so': 'android.hardware.graphics.common-V7-ndk.so',
    'android.hardware.graphics.allocator-V1-ndk.so': 'android.hardware.graphics.allocator-V2-ndk.so',
}

# Android 13 libbase string overloads (hardware/lineage/compat libbase_shim).
LIBBASE_SHIM = ('libcodec2_hidl@1.0', 'libcodec2_hidl@1.1', 'libcodec2_hidl@1.2')


# Implicit for every cc module.
BIONIC = ('libc.so', 'libm.so', 'libdl.so', 'libc++.so')


def renamed(lib):
    return f'{lib}-v33'


def patchelf(*args):
    return subprocess.run([PATCHELF, *args], capture_output=True, text=True, check=True).stdout


def main():
    stock = sys.argv[1]
    prebuilt_dir = os.path.join(HERE, 'lib64')
    os.makedirs(prebuilt_dir, exist_ok=True)
    for lib, origin in LIBS.items():
        if origin == 'lineage':
            continue
        src = (os.path.join(VNDK33, f'{lib}.so') if origin == 'vndk33'
               else os.path.join(stock, 'lib64', f'{lib}.so'))
        dst = os.path.join(prebuilt_dir, f'{renamed(lib)}.so')
        shutil.copyfile(src, dst)
        patchelf('--set-soname', f'{renamed(lib)}.so', dst)
        if lib in LIBBASE_SHIM:
            patchelf('--add-needed', 'libbase_shim.so', dst)
        for dep in patchelf('--print-needed', dst).split():
            base = dep[:-3]
            if base in LIBS:
                patchelf('--replace-needed', dep, f'{renamed(base)}.so', dst)
            elif dep in REPLACE:
                patchelf('--replace-needed', dep, REPLACE[dep], dst)

    with open(os.path.join(HERE, 'Android.bp'), 'w') as bp:
        bp.write('// Generated by generate.py; see that file for details.\n')
        for lib in (l for l, o in LIBS.items() if o != 'lineage'):
            so = os.path.join(prebuilt_dir, f'{renamed(lib)}.so')
            deps = ''.join(f'        "{d[:-3]}",\n' for d in patchelf('--print-needed', so).split()
                           if d not in BIONIC)
            bp.write(f'''
cc_prebuilt_library_shared {{
    name: "{renamed(lib)}",
    vendor: true,
    compile_multilib: "64",
    srcs: ["lib64/{renamed(lib)}.so"],
    shared_libs: [
{deps}    ],
    check_elf_files: false,
    strip: {{ none: true }},
}}
''')
    print('\n'.join(f'{renamed(lib)}.so' for lib in LIBS))


if __name__ == '__main__':
    main()
