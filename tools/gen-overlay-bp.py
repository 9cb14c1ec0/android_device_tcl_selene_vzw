#!/usr/bin/env python3
# Regenerate prebuilt/overlay/{Android.bp,packages.mk} from the APKs in
# prebuilt/overlay (copied from the stock /vendor/overlay).
import os
here = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'prebuilt', 'overlay')
apks = sorted(os.path.relpath(os.path.join(r, f), here)
              for r, _, fs in os.walk(here) for f in fs if f.endswith('.apk'))
out = ['//\n// Stock TCL/MediaTek vendor RROs (/vendor/overlay), presigned.\n// Generated by tools/gen-overlay-bp.py\n//\n']
names = []
for f in apks:
    d, b = os.path.dirname(f), os.path.basename(f)
    name = 'selene_vendor_overlay_' + f.replace('/', '_').replace('.apk', '').replace('-', '_')
    names.append(name)
    m = ['prebuilt_overlay {', f'    name: "{name}",', f'    src: "{f}",', f'    filename: "{b}",', '    vendor: true,']
    if d:
        m.append(f'    relative_install_path: "{d}",')
    m.append('}\n')
    out.append('\n'.join(m))
open(os.path.join(here, 'Android.bp'), 'w').write('\n'.join(out))
open(os.path.join(here, 'packages.mk'), 'w').write(
    '# Generated by tools/gen-overlay-bp.py\nPRODUCT_PACKAGES += \\\n' +
    ' \\\n'.join('    ' + n for n in names) + '\n')
print(len(names))
