# Blobs that link a stock library installed as -v33 (tools/v33-paths.txt,
# generated by tools/gen-proprietary-files.py into tools/v33-needed.txt).
# 1-tuple keys, so these merge with the fixups below for the same blob.
v33_fixups: blob_fixups_user_type = {}
with open(os.path.join(TOOLS, 'v33-needed.txt')) as f:
    for line in f:
        blob, *libs = line.split()
        fixup = blob_fixup()
        for lib in libs:
            fixup = fixup.replace_needed(lib, lib.removesuffix('.so') + '-v33.so')
        v33_fixups[(blob,)] = fixup


def codec2_v33() -> blob_fixup:
    fixup = blob_fixup()
    for lib in CODEC2_V33:
        fixup = fixup.replace_needed(f'{lib}.so', f'{lib}-v33.so')
    return fixup


