TOOLS = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'tools')

# Stock blobs that share a name with an AOSP source module are kept as
# prebuilts named <lib>_vendor (tools/copy-only-libs.txt, MODULE_SUFFIX in
# proprietary-files.txt); point blob dependencies at those, so the build does
# not also install its own Android 15 builds of them. Blobs at a path an AOSP
# vendor module also installs to are renamed -v33 instead (below).
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'proprietary-files.txt')) as f:
    copy_only_libs = tuple(sorted({
        os.path.basename(line.split(';')[0]).removesuffix('.so')
        for line in f
        if 'MODULE_SUFFIX=_vendor' in line
    }))


def lib_fixup_vendor_suffix(lib: str, partition: str, *args, **kwargs):
    return f'{lib}_{partition}' if partition == 'vendor' else None


lib_fixups: lib_fixups_user_type = {
    **lib_fixups,
    copy_only_libs: lib_fixup_vendor_suffix,
}

